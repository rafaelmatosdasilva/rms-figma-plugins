/**
 * Returns an <svg><use> snippet for a Figma variable resolved type.
 * @param {string} type  - 'COLOR' | 'FLOAT' | 'STRING' | 'BOOLEAN'
 * @param {number} [size=12]
 */
// Figma's resolvedType enum → DS icon id. A lookup, not concatenation: the DS names
// the numeric one "number" while the API calls it FLOAT, so the two vocabularies
// cannot be bridged by string-building.
var VAR_TYPE_ICON = {
  COLOR:   'icon-var-color',
  FLOAT:   'icon-var-number',
  STRING:  'icon-var-string',
  BOOLEAN: 'icon-var-boolean',
};

function varTypeIconHtml(type, size) {
  size = size || 12;
  var id = '#' + (VAR_TYPE_ICON[type] || 'icon-var-number'); // fallback
  var renderSize = size; // DS grid only — no off-grid +2
  return '<svg width="' + renderSize + '" height="' + renderSize + '" style="flex-shrink:0"><use href="' + id + '"/></svg>';
}

// ── Universal tooltip engine ──────────────────────────────────────────────────
(function () {
  const PAD = 10, DELAY = 1000;
  const tt = document.getElementById('tt');
  let showTimer = null, cursorX = 0, cursorY = 0, activeEl = null;

  function place() {
    const vw = window.innerWidth, vh = window.innerHeight;
    const tw = tt.offsetWidth, th = tt.offsetHeight;
    let x = cursorX + 14, y = cursorY + 14;
    if (x + tw + PAD > vw) x = cursorX - tw - 8;
    if (y + th + PAD > vh) y = cursorY - th - 8;
    tt.style.left = x + 'px';
    tt.style.top  = y + 'px';
  }

  function show(el) {
    tt.textContent = el.dataset.tip;
    tt.classList.remove('tt-visible');
    clearTimeout(showTimer);
    showTimer = setTimeout(() => {
      place();
      tt.classList.add('tt-visible');
    }, DELAY);
  }

  function hide() {
    clearTimeout(showTimer);
    tt.classList.remove('tt-visible');
    activeEl = null;
  }

  document.addEventListener('mousemove', (e) => {
    cursorX = e.clientX;
    cursorY = e.clientY;
    if (tt.classList.contains('tt-visible')) place();
  });

  document.addEventListener('mouseover', (e) => {
    const el = e.target.closest('[data-tip]');
    if (el && el !== activeEl) {
      activeEl = el;
      show(el);
    } else if (!el) {
      hide();
    }
  });

  document.addEventListener('mouseout', (e) => {
    const el = e.target.closest('[data-tip]');
    if (el && !el.contains(e.relatedTarget)) hide();
  });

  document.addEventListener('mousedown', hide);
  document.addEventListener('scroll',    hide, true);
  document.addEventListener('keydown',   hide, true);
})();

