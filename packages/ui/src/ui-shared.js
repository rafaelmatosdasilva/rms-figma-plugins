var toastTimer = null;

// opts: { error: true } → negative fill + warning icon, and stays up longer.
// Without it the toast is the success one: check icon, success fill.
function showToast(msg, opts) {
  const isError = !!(opts && opts.error);
  if (toastTimer) clearTimeout(toastTimer);
  const cls  = isError ? 'toast toast-error' : 'toast';
  const icon = isError ? '#icon-warning' : '#icon-check';
  document.getElementById('toast-container').innerHTML =
    `<div class="${cls}"><span class="toast-icon"><svg width="16" height="16"><use href="${icon}"/></svg></span><span>${msg}</span></div>`;
  // A failure is worth more reading time than a confirmation.
  toastTimer = setTimeout(dismissToast, isError ? 8000 : 5000);
}

// Every plugin reports failures the same way — negative toast, no inline banner.
function showError(msg) { showToast(msg, { error: true }); }

function dismissToast() {
  if (toastTimer) { clearTimeout(toastTimer); toastTimer = null; }
  const t = document.querySelector('.toast');
  if (!t) return;
  t.classList.add('toast-out');
  const onEnd = (ev) => {
    if (ev.animationName !== 'toast-out') return;
    t.removeEventListener('animationend', onEnd);
    document.getElementById('toast-container').innerHTML = '';
  };
  t.addEventListener('animationend', onEnd);
}

